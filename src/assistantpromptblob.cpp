QString assistantDecodePolicyFragment()
{
    const QByteArray key = materializeKey();
    QByteArray plain;
    plain.resize(kPolicyLen);
    for (int i = 0; i < kPolicyLen; ++i)
        plain[i] = static_cast<char>(kPolicyBlob[i] ^ static_cast<unsigned char>(key.at(i % key.size())));

    if (fnv1a32(plain) != kPolicyFnv)
        return {};

    // Wipe key material (best-effort; not a security boundary).
    QByteArray wipe = key;
    wipe.fill(0);

    return QString::fromUtf8(plain);
}
