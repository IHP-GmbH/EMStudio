quint32 fnv1a32(const QByteArray &data)
{
    quint32 h = 2166136261u;
    for (unsigned char b : data) {
        h ^= b;
        h *= 16777619u;
    }
    return h;
}

QByteArray materializeKey()
{
    // Split so a single contiguous key string is not sitting next to the blob.
    const unsigned char a[] = {0xA7, 0x3C, 0x91, 0x5E};
    const unsigned char b[] = {0x2B, 0xD4, 0x08, 0xF1};
    const unsigned char c[] = {0x6A, 0xC3, 0x19, 0x7E};
    const unsigned char d[] = {0xB5, 0x44, 0xE0, 0x2D};
    QByteArray key;
    key.reserve(16);
    key.append(reinterpret_cast<const char *>(a), 4);
    key.append(reinterpret_cast<const char *>(b), 4);
    key.append(reinterpret_cast<const char *>(c), 4);
    key.append(reinterpret_cast<const char *>(d), 4);
    return key;
}

